# frozen_string_literal: true

# Generates crates/etassia-core/src/text/tables.rs from the Ruby Etassia text
# tables, so no number is copied by hand. Run from a etassia checkout:
#
#   cd $ETASSIA && ruby /path/to/etassia-rs/scripts/generate_text_tables.rb
#
# Env: TEXT_TABLES_OUT overrides the output path.
$LOAD_PATH.unshift(File.join(Dir.pwd, "lib"))
require "etassia/text_measurement"
require "etassia/text_measurement/times_advances"
require "etassia/text_measurement/trebuchet_kerning"
require "etassia/layout/timeline_text"

OUT = ENV.fetch("TEXT_TABLES_OUT",
                File.expand_path("../crates/etassia-core/src/text/tables.rs", __dir__))
TM = Etassia::TextMeasurement

def advances(name, table)
  rows = table.sort.map { |cp, adv| format("(0x%04X, %d)", cp, adv) }
  body = rows.each_slice(6).map { |r| "    #{r.join(', ')}," }.join("\n")
  "pub static #{name}: &[(u32, u16)] = &[\n#{body}\n];\n"
end

def ranges(name, regex, pinned = [])
  cps = (0..0x10FFFF).select do |cp|
    next false if (0xD800..0xDFFF).cover?(cp)

    cp.chr(Encoding::UTF_8).match?(regex)
  end
  cps |= pinned
  runs = cps.sort.chunk_while { |a, b| b == a + 1 }.map { |c| [c.first, c.last] }
  rows = runs.map { |a, b| format("(0x%X, 0x%X)", a, b) }
  body = rows.each_slice(6).map { |r| "    #{r.join(', ')}," }.join("\n")
  "pub static #{name}: &[(u32, u32)] = &[\n#{body}\n];\n"
end

kern = Etassia::TextMeasurement::TrebuchetKerning::PAIRS.map do |k, v|
  format("(%p, %d)", k, v)
end.join(", ")
units = Etassia::Layout::TimelineText::BASIC_LATIN_UNITS

File.write(OUT, <<~RS)
  // GENERATED by scripts/generate_text_tables.rb from Ruby #{RUBY_VERSION}
  // (Unicode #{RbConfig::CONFIG['UNICODE_VERSION']}); do not edit by hand.
  #![cfg_attr(rustfmt, rustfmt_skip)]

  /// Arial (Liberation Sans) advances in per-mille em, sorted by codepoint.
  #{advances('ARIAL', TM::ArialAdvances::TABLE)}
  /// Trebuchet MS advances in per-mille em, sorted by codepoint.
  #{advances('TREBUCHET', TM::TrebuchetAdvances::TABLE)}
  /// Times New Roman advances in per-mille em, sorted by codepoint.
  #{advances('TIMES', TM::TimesAdvances::TABLE)}
  /// Inclusive ranges matching Ruby's `[\\p{Mn}\\p{Me}\\p{Cf}\\p{Cc}]`.
  #{ranges('ZERO_WIDTH', TM::ZERO_WIDTH)}
  /// Inclusive ranges matching `\\p{Extended_Pictographic}` plus the pinned set.
  #{ranges('EMOJI', TM::EMOJI, TM::PINNED_PICTOGRAPHS)}
  /// Codepoints whose width comes from ligature substitution.
  pub static OUTLIERS: &[(u32, u16)] = &[#{TM::OUTLIERS.sort.map { |c, a| format('(0x%X, %d)', c, a) }.join(', ')}];

  /// Trebuchet kern pairs, design units.
  pub static TREBUCHET_KERNING: &[(&str, i32)] = &[#{kern}];

  /// Exact Trebuchet hmtx units for U+0020..U+007E (timeline text).
  pub static TIMELINE_BASIC_LATIN_UNITS: &[i32] = &[#{units.join(', ')}];
RS
puts "wrote #{OUT}"
