# Regenerates theme_data.rs from the Ruby builtin themes.
# Usage: cd <etassia ruby checkout> && bundle exec ruby <this file> > theme_data.rs
require "yaml"
puts "// @generated by gen_theme.rb from lib/etassia/theme/builtin/*.yml. Do not edit."
puts "use super::theme::ThemeData;"
puts
names = []
Dir.glob(File.join(File.expand_path("lib/etassia/theme/builtin"), "*.yml")).sort.each do |path|
  y = YAML.load_file(path)
  n = y["name"]; names << n
  strs = []; nums = []; bools = []; pals = []
  %w[colors typography shapes spacing effects].each do |sec|
    (y[sec] || {}).each do |k, v|
      key = "#{sec}.#{k}"
      case v
      when String then strs << [key, v]
      when Float, Integer then nums << [key, v.to_f]
      when true, false then bools << [key, v]
      when Array then pals << [k, v]
      end
    end
  end
  puts "pub(super) static #{n.upcase}: ThemeData = ThemeData {"
  puts "    name: #{n.inspect},"
  puts "    description: #{y['description'].inspect},"
  puts "    strings: &[#{strs.map { |k, v| "(#{k.inspect}, #{v.inspect})" }.join(', ')}],"
  puts "    numbers: &[#{nums.map { |k, v| "(#{k.inspect}, #{v.inspect})" }.join(', ')}],"
  puts "    bools: &[#{bools.map { |k, v| "(#{k.inspect}, #{v})" }.join(', ')}],"
  puts "    palettes: &[#{pals.map { |k, v| "(#{k.inspect}, &[#{v.map(&:inspect).join(', ')}])" }.join(', ')}],"
  puts "};"
  puts
end
puts "pub(super) static ALL: &[&ThemeData] = &[#{names.map { |n| "&#{n.upcase}" }.join(', ')}];"
